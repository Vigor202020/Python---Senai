# O for (Fórmula de Repetição), serve para percorrermos uma sequencia de elementos

for i in range (0, 11):    # i = (nada), in range (0,11) = na sequencia de elementos de 0,1,2,3...11.
    for j in range(0,11):   # Para o j começar a ser completado a Primeira sequencia deve se completar para a Segunda j começar
        print(f"{i} x {j} = {i * j}")   # Aqui só fassemos a ilusão de uma calculadora
